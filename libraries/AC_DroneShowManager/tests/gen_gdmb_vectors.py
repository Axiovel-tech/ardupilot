#!/usr/bin/env python3
"""
Embed the .gdm golden vectors in a C++ header for test_gdmb.cpp.

The vectors are owned by AxioStack (contracts/gdm-vectors/, generated by
gdm_ref.py from contracts/gdm-format.md). This script copies them verbatim:
the .gdmb bytes, the reject cases with their expected error codes, the accept
cases and the evaluation samples of expected.json. Vectors and edge cases
under provisional/ (spec §4.11) are tagged so that the test reads them with
GDMB_PARSE_PROVISIONAL; a v1 reader refuses them.

Usage:
    gen_gdmb_vectors.py <AxioStack>/contracts/gdm-vectors [source-description]

Rewrites gdmb_vectors.h next to this script. Rerun it whenever the contract's
vectors change, and say which AxioStack revision they came from.
"""

import json
import sys
from pathlib import Path

VECTORS = ["flat-single", "provisional/flat-rth", "provisional/maneuver-single"]
EDGE_INDEXES = ["edge/index.json", "provisional/edge/index.json"]


def c_bytes(data: bytes) -> str:
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    return "\n".join(lines)


def c_real(v) -> str:
    return repr(float(v))


def c_vec(vals) -> str:
    return "{ " + ", ".join(c_real(v) for v in vals) + " }"


def ident(name: str) -> str:
    return name.replace("-", "_").replace(".", "_")


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2

    root = Path(sys.argv[1])
    source = sys.argv[2] if len(sys.argv) > 2 else str(root)
    out = []
    out.append("// Generated by gen_gdmb_vectors.py. Do not edit.")
    out.append(f"// Source: {source}")
    out.append("#pragma once")
    out.append("")
    out.append("#include <stddef.h>")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("namespace gdmb_vectors {")
    out.append("")
    out.append("struct Sample {")
    out.append("    int64_t t_us;")
    out.append("    const char* regime;")
    out.append("    double p[3], v[3], a[3];")
    out.append("    double yaw, yaw_rate;            // FLAT and hold samples")
    out.append("    double q[4], omega[3], omega_dot[3], thrust;  // maneuver samples")
    out.append("};")
    out.append("")
    out.append("struct Vector {")
    out.append("    const char* name;")
    out.append("    const uint8_t* data;")
    out.append("    size_t size;")
    out.append("    uint32_t crc32;")
    out.append("    uint32_t mavftp_file_crc32;")
    out.append("    const Sample* samples;")
    out.append("    size_t num_samples;")
    out.append("    bool provisional;  // read with GDMB_PARSE_PROVISIONAL (spec §4.11)")
    out.append("};")
    out.append("")
    out.append("struct Edge {")
    out.append("    const char* name;")
    out.append("    const uint8_t* data;")
    out.append("    size_t size;")
    out.append("    const char* code;  // expected error code, nullptr for accept vectors")
    out.append("    bool provisional;  // read with GDMB_PARSE_PROVISIONAL (spec §4.11)")
    out.append("};")
    out.append("")

    vector_rows = []
    for name in VECTORS:
        data = (root / name / "d01.gdmb").read_bytes()
        expected = json.loads((root / name / "expected.json").read_text())
        gd = expected["gdmb"]["d01"]
        assert gd["size"] == len(data), name
        n = ident(name.replace("/", "_"))
        out.append(f"static const uint8_t {n}_gdmb[] = {{")
        out.append(c_bytes(data))
        out.append("};")
        out.append("")
        out.append(f"static const Sample {n}_samples[] = {{")
        for s in expected["samples"]["d01"]:
            zero3 = [0.0, 0.0, 0.0]
            out.append(
                "    { "
                + f"{s['t_us']}, \"{s['regime']}\", "
                + f"{c_vec(s['p'])}, {c_vec(s['v'])}, {c_vec(s['a'])}, "
                + f"{c_real(s.get('yaw', 0.0))}, {c_real(s.get('yaw_rate', 0.0))}, "
                + f"{c_vec(s.get('q', [0.0] * 4))}, {c_vec(s.get('omega', zero3))}, "
                + f"{c_vec(s.get('omega_dot', zero3))}, {c_real(s.get('thrust', 0.0))} }},"
            )
        out.append("};")
        out.append("")
        vector_rows.append(
            f"    {{ \"{name}\", {n}_gdmb, sizeof({n}_gdmb), {gd['crc32']}u, {gd['mavftp_file_crc32']}u, "
            f"{n}_samples, sizeof({n}_samples) / sizeof({n}_samples[0]), "
            f"{'true' if expected.get('provisional') else 'false'} }},"
        )

    edge_rows = []
    for index_path in EDGE_INDEXES:
        index = json.loads((root / index_path).read_text())
        edge_dir = (root / index_path).parent
        provisional = index.get("mode") == "provisional"
        for kind in ("reject", "accept"):
            for e in index[kind]:
                if e.get("file") is None:
                    # The oversize case is built by the test from its recipe
                    continue
                data = bytes.fromhex((edge_dir / e["file"]).read_text())
                n = ident(("provisional_" if provisional else "") + e["file"])
                out.append(f"static const uint8_t {n}[] = {{")
                out.append(c_bytes(data))
                out.append("};")
                out.append("")
                code = f"\"{e['code']}\"" if kind == "reject" else "nullptr"
                name = ("provisional/" if provisional else "") + e["file"]
                edge_rows.append(f"    {{ \"{name}\", {n}, sizeof({n}), {code}, {'true' if provisional else 'false'} }},")

    out.append("static const Vector vectors[] = {")
    out.extend(vector_rows)
    out.append("};")
    out.append("")
    out.append("static const Edge edges[] = {")
    out.extend(edge_rows)
    out.append("};")
    out.append("")
    out.append("}  // namespace gdmb_vectors")
    out.append("")

    dest = Path(__file__).resolve().parent / "gdmb_vectors.h"
    dest.write_text("\n".join(out))
    print(f"wrote {dest} ({len(vector_rows)} vectors, {len(edge_rows)} edge cases)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
